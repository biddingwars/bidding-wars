/* ============================================================================
   us-view.js — draws the US results map: the contiguous states on satellite-style
   imagery, the winner's states in gold with markers, callouts for the crowded
   Northeast, and Alaska / Hawaii insets ONLY when the winner owns them.

   The outlines and imagery are generated by test/build-us-map.js into us-map.js
   (state paths, projected with Albers equal-area conic) and us-map.webp / us-ak.webp
   / us-hi.webp. This file only draws; it needs no network and loads us-map.js
   lazily the first time a results screen asks for it. View code only: no game rule.
   ========================================================================== */
(function (root) {
  'use strict';
  const CROWDED = ['NH', 'VT', 'MA', 'RI', 'CT', 'NJ', 'DE', 'MD'];       // too small / close to label in place
  const MARGIN = 170, BAND = 215, PILL_W = 40, PILL_H = 22;               // viewBox units / screen px

  let dataP = null;
  function data() {
    if (root.USMAP) return Promise.resolve(root.USMAP);
    if (dataP) return dataP;
    dataP = new Promise(function (resolve, reject) {
      const s = root.document.createElement('script');
      s.src = 'us-map.js'; s.async = true;
      s.onload = function () { root.USMAP ? resolve(root.USMAP) : reject(new Error('us-map.js did not define USMAP')); };
      s.onerror = function () { s.remove(); dataP = null; reject(new Error('Could not load us-map.js')); };
      root.document.head.appendChild(s);
    });
    return dataP;
  }

  const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

  /* pure layout: where every label, pin and leader goes, in viewBox units. Exported for the tests. */
  function layout(M, wonIds, scale) {
    const won = wonIds.filter((v, i, a) => a.indexOf(v) === i);
    const hasAK = won.includes('AK'), hasHI = won.includes('HI');
    const main = won.filter(id => M.main.states[id]);
    const crowded = main.filter(id => CROWDED.includes(id)), inline = main.filter(id => !CROWDED.includes(id));
    const W = M.main.w, H = M.main.h, VW = W + (crowded.length ? MARGIN : 0), VH = H + (hasAK || hasHI ? BAND : 0);
    const pw = PILL_W / scale, ph = PILL_H / scale, pin = 5.5 / scale;

    const pins = main.map(id => ({ id, x: M.main.states[id].c[0], y: M.main.states[id].c[1] }));
    const placed = [], labels = [];
    const hit = (a, b) => Math.abs(a.x - b.x) < pw && Math.abs(a.y - b.y) < ph;
    inline.slice().sort((a, b) => M.main.states[a].c[1] - M.main.states[b].c[1] || M.main.states[a].c[0] - M.main.states[b].c[0]).forEach(id => {
      const c = M.main.states[id].c;
      let pos = null;
      for (const dy of [0, 1, -1, 2, -2, 3, -3]) {                         // nudge down/up in label-heights until it is free
        const p = { x: c[0], y: c[1] + dy * ph * 1.05 };
        if (!placed.some(q => hit(p, q))) { pos = p; break; }
      }
      if (!pos) return;                                                    // too crowded to label without overlap: the pin stays, the pill is dropped
      placed.push(pos); labels.push({ id, x: pos.x, y: pos.y, lead: Math.abs(pos.y - c[1]) > ph * .6 ? [c[0], c[1]] : null });
    });
    /* callouts for the Northeast sit in the margin to the right, spread so none overlap, joined by leaders */
    const col = crowded.slice().sort((a, b) => M.main.states[a].c[1] - M.main.states[b].c[1]);
    const ch = 16 / scale, gap = ch * 1.1, callouts = [];                   // callout pills are smaller (CSS .um-c) so eight fit a phone-sized map
    col.forEach((id, i) => {
      const c = M.main.states[id].c;
      let y = Math.max(c[1], ch * .6); if (i && y < callouts[i - 1].y + gap) y = callouts[i - 1].y + gap;
      callouts.push({ id, x: W + MARGIN * .5, y, from: c });
    });
    const over = callouts.length ? callouts[callouts.length - 1].y - (H - ch * .6) : 0;
    if (over > 0) callouts.forEach(c => { c.y -= over; });                // keep the column inside the map
    return { VW, VH, W, H, hasAK, hasHI, pins, labels, callouts, pw, ph, pin };
  }

  /* host: the element to fill. items: the won pack items. o: { label(item) → string,
     aria, reduced }. Resolves with { stop } (nothing to tear down: it is static SVG + HTML). */
  function render(host, items, o) {
    o = o || {};
    return data().then(function (M) {
      const byId = new Map(items.map(i => [i.id, i]));
      const scale0 = Math.max(.1, (host.clientWidth || 360) / (M.main.w + MARGIN));
      const L = layout(M, items.map(i => i.id), scale0);
      const { VW, VH, W, H } = L;
      const pct = (x, y) => 'left:' + (x / VW * 100).toFixed(2) + '%;top:' + (y / VH * 100).toFixed(2) + '%';
      const win = id => '<path class="um-win" d="' + M.main.states[id].d + '"/>';
      const glow = id => '<path class="um-glow" d="' + M.main.states[id].d + '"/>';
      let svg = '<image href="' + M.main.image + '" x="0" y="0" width="' + W + '" height="' + H + '" preserveAspectRatio="none"/>' +
        '<path class="um-dim" fill-rule="evenodd" d="M0 0H' + W + 'V' + H + 'H0Z' + M.main.outline + '"/>' +
        '<g class="um-b">' + Object.keys(M.main.states).map(id => '<path d="' + M.main.states[id].d + '"/>').join('') + '</g>' +
        '<g class="um-wins">' + L.pins.map((p, i) => '<g style="animation-delay:' + (i * 55) + 'ms">' + glow(p.id) + win(p.id) + '</g>').join('') + '</g>';
      L.callouts.forEach(c => { svg += '<polyline class="um-lead" points="' + c.from[0] + ',' + c.from[1] + ' ' + (W + 6) + ',' + c.y + ' ' + (c.x - L.pw * .6) + ',' + c.y + '"/>'; });
      L.labels.forEach(l => { if (l.lead) svg += '<line class="um-lead" x1="' + l.lead[0] + '" y1="' + l.lead[1] + '" x2="' + l.x + '" y2="' + l.y + '"/>'; });
      svg += L.pins.map(p => '<circle class="um-pin" cx="' + p.x + '" cy="' + p.y + '" r="' + L.pin.toFixed(1) + '"/>').join('');

      /* insets, only for the states the winner owns */
      let ix = 16, html = '';
      [['AK', 'AK'], ['HI', 'HI']].forEach(function (pair) {
        const id = pair[0]; if (!byId.has(id)) return;
        const B = M[id], y = H + 14, st = B.states[id];
        svg += '<g transform="translate(' + ix + ' ' + y + ')"><rect class="um-frame" x="0" y="0" width="' + B.w + '" height="' + B.h + '" rx="10"/>' +
          '<image href="' + B.image + '" x="0" y="0" width="' + B.w + '" height="' + B.h + '" preserveAspectRatio="none" clip-path="inset(0 round 10px)"/>' +
          '<g class="um-wins"><g>' + '<path class="um-glow" d="' + st.d + '"/><path class="um-win" d="' + st.d + '"/>' + '</g></g>' +
          '<circle class="um-pin" cx="' + st.c[0] + '" cy="' + st.c[1] + '" r="' + L.pin.toFixed(1) + '"/></g>';
        html += '<span class="glabel um-l" style="' + pct(ix + st.c[0], y + st.c[1] - 22) + '">' + esc(o.label ? o.label(byId.get(id)) : id) + '</span>';
        ix += B.w + 16;
      });
      L.labels.forEach(l => { html += '<span class="glabel um-l" style="' + pct(l.x, l.y) + '">' + esc(o.label ? o.label(byId.get(l.id)) : l.id) + '</span>'; });
      L.callouts.forEach(c => { html += '<span class="glabel um-l um-c" style="' + pct(c.x, c.y) + '">' + esc(o.label ? o.label(byId.get(c.id)) : c.id) + '</span>'; });

      host.classList.toggle('still', !!o.reduced);
      host.style.aspectRatio = VW + ' / ' + VH;
      host.innerHTML = '<svg viewBox="0 0 ' + VW + ' ' + VH + '" role="img" aria-label="' + esc(o.aria || '') + '" preserveAspectRatio="xMidYMid meet">' + svg + '</svg>' + html;
      return { stop() {}, layout: L };
    });
  }

  const API = { render, layout, data, CROWDED };
  if (typeof module === 'object' && module.exports) module.exports = API; else root.USView = API;
})(typeof self !== 'undefined' ? self : this);
