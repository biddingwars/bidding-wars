/* Generates ../pack-capitals.js from two committed inputs, so the pack can always be rebuilt and checked:
     test/wup2018-f13-capitals.json   the UN numbers, copied unchanged (see its "source", "vintage", "license", "sha256_xls")
     test/capitals-content.json       names in five languages, the Europe list, taunts, level labels
   Run: node test/make-pack-capitals.js          (the tests fail if the pack drifts from the inputs)
   The choice of capital for countries with several is in CAPITALS-SOURCES.md. Price curve and bot calibration live HERE (CAL below). */
const fs = require('fs'), path = require('path');
const W = JSON.parse(fs.readFileSync(path.join(__dirname, 'wup2018-f13-capitals.json'), 'utf8'));
const C = JSON.parse(fs.readFileSync(path.join(__dirname, 'capitals-content.json'), 'utf8'));
const EUROPE = new Set(C.europe);

/* ---- calibration (re-measured with `node test/economy.js capitals`) ------------------------------------------------ */
const CAL = {
  /* fair price (EUR) at a city population (millions): log-log anchors, monotone cubic in between, whole euros, minimum EUR 1 */
  anchors: [[0.001, 1], [0.15, 1], [0.3, 2.2], [0.6, 3.9], [1, 6], [2, 11.5], [3, 17], [5, 25], [8, 37], [12, 52], [20, 76], [30, 98], [40, 115]],
  ratio: { tiny: 2.0, giant: 1.45, from: 0.05, to: 40 }, // max / ideal eases from 2.0 (tiniest) to 1.45 (Tokyo), forced non-decreasing
  budgets: { beginner: { 5: 25, 10: 50, 15: 75, 20: 100, 30: 150 }, medium: { 5: 50, 10: 100, 15: 150, 20: 200, 30: 300 }, expert: { 5: 50, 10: 100, 15: 150, 20: 200, 30: 300 } },
  mediumMin: 2, // Medium: capitals over 2 million (70 of 195)
  bot: {
    limitMul: { beginner: { 5: 1.211, 10: 0.838, 15: 0.769, 20: 0.826, 30: 0.991 }, medium: { 5: 0.796, 10: 0.872, 15: 0.956, 20: 0.88, 30: 0.891 }, expert: { 5: 1.55, 10: 1.419, 15: 1.261, 20: 1.405, 30: 1.782 }},
    premium: { top: 5, pct: { beginner: 0.5, medium: 0.15, expert: 0.15 } },
    pacing: { gamma: 0.5, lo: 0.7, hi: 1.5 },
    knockout: { kappa: { beginner: 1.221, medium: 0.484, expert: 0.64 } },
    mood: { k: 0.25, up: 0.2, down: 0.15 },
    wallet: { lo: 0.7 },
    noise: { beginner: 0.376, medium: 0.377, expert: 0.471 },
    crowd: { beginner: -0.15, medium: 0.15, expert: 0.2 },                // v50: the walk-away changes by this share per extra seat at a table of 3-4 (never in a duel); found with a fair-value human against 2-3 bots

    efficiency: { gamma: { beginner: 0.72, medium: 0.989, expert: 0.598 }, lo: { beginner: 0.4, medium: 0.272, expert: 0.27 }, hi: { beginner: 3.076, medium: 2.623, expert: 2.522 }, pick: { beginner: 1.909, medium: 1.85, expert: 1.903 } },
    decisive: { share: { beginner: 0.251, medium: 0.374, expert: 0.209 }, minPrice: { beginner: 0.8, medium: 1.2, expert: 1.2 } },   // all-in only for a lot whose fair price is at least this share of the bot's current purse (1.2 = one it cannot really afford: Delhi yes; Seoul and Washington no)
    creeperGuard: { raises: 3 },
    temperaments: { weights: [25, 50, 25], bigRank: 10, spread: { 5: 0.06, 10: 0.06, 15: 0.05, 20: 0.04, 30: 0.04 }, conservative: { step: 0.75, big: 0.95 }, aggressive: { step: 1.25, big: 1.05, reserveCap: 3 } }
  }
};
function build() {
const items = W.lots.map(r => {
  const name = Object.assign({}, C.names[r.id]);
  if (!name.en) throw new Error('no name for ' + r.id);
  const o = { id: r.id, name, value: r.popThousands / 1000, lat: r.lat, lon: r.lon };
  if (EUROPE.has(r.id)) o.tags = ['europe'];
  return o;
});
if (items.length !== 195 || new Set(items.map(i => i.id)).size !== 195) throw new Error('expected 195 distinct lots, got ' + items.length);
const js = v => JSON.stringify(v);

const pack = `/* ============================================================================
   pack-capitals.js — the "Capital Cities" content pack: 195 capitals (the 193 UN member states, Vatican City and
   Taiwan's Taipei), population of the capital's urban agglomeration (millions) as the score.
   GENERATED by test/make-pack-capitals.js — edit the inputs, not this file.

   Population: ${W.source}
   ${W.table}. ${W.vintage}.
   ${W.license}.
   Where a country has several capitals the seat of government is used; the choices and every caveat are in CAPITALS-SOURCES.md.
   Pack format: see CLAUDE.md "Adding a pack".
   ========================================================================== */
(function (root) {
  /* ---- prices -------------------------------------------------------------------------------------------------
     One smooth, monotone curve for all 195 capitals (no bands, so a bigger city never costs less): a monotone cubic
     (Fritsch-Carlson) through log-log anchors [population in millions, fair price in EUR], rounded to whole euros, minimum
     EUR 1. The bot's ceiling is ideal x ratio, the ratio easing from ${CAL.ratio.tiny} for the tiniest capitals to ${CAL.ratio.giant} for Tokyo and forced
     non-decreasing. test/golden-capitals.json pins every price. */
  const ANCHORS = ${js(CAL.anchors)};
  const RATIO = ${js(CAL.ratio)};
  function pchip(xs, ys) {
    const n = xs.length, h = [], d = [], m = new Array(n).fill(0);
    for (let i = 0; i < n - 1; i++) { h.push(xs[i + 1] - xs[i]); d.push((ys[i + 1] - ys[i]) / h[i]); }
    for (let i = 1; i < n - 1; i++) { if (d[i - 1] * d[i] <= 0) m[i] = 0; else { const w1 = 2 * h[i] + h[i - 1], w2 = h[i] + 2 * h[i - 1]; m[i] = (w1 + w2) / (w1 / d[i - 1] + w2 / d[i]); } }
    m[0] = d[0]; m[n - 1] = d[n - 2];
    return x => {
      if (x <= xs[0]) return ys[0]; if (x >= xs[n - 1]) return ys[n - 1];
      let i = 0; while (x > xs[i + 1]) i++;
      const t = (x - xs[i]) / h[i], t2 = t * t, t3 = t2 * t;
      return (2 * t3 - 3 * t2 + 1) * ys[i] + (t3 - 2 * t2 + t) * h[i] * m[i] + (-2 * t3 + 3 * t2) * ys[i + 1] + (t3 - t2) * h[i] * m[i + 1];
    };
  }
  function priceTable(items) {
    const f = pchip(ANCHORS.map(a => Math.log(a[0])), ANCHORS.map(a => Math.log(a[1])));
    const ideal = v => Math.max(1, Math.round(Math.exp(f(Math.log(Math.max(v, ANCHORS[0][0]))))));
    const ratio = v => { const t = Math.min(1, Math.max(0, Math.log(v / RATIO.from) / Math.log(RATIO.to / RATIO.from))); return RATIO.tiny + (RATIO.giant - RATIO.tiny) * t * t * (3 - 2 * t); };
    const out = new Map(); let prevMax = 0;
    items.map((it, i) => i).sort((a, b) => items[a].value - items[b].value).forEach(i => {
      const it = items[i], p = ideal(it.value), mx = Math.max(p, Math.round(p * ratio(it.value)), prevMax);
      prevMax = mx; out.set(it.id, { ideal: p, max: mx });
    });
    return out;
  }
  const pack = {
    id: 'capitals',
    title: ${js(C.title)},
    noun: ${js(C.noun)},
    iconKind: 'flag', // item id is the ISO code of the country → its flag marks the capital
    currency: { symbol: '€' },
    budgetPerLot: 10, // Medium's rate; economy.budgets below is what the auction really uses
    lots: { options: [5, 10, 15, 20, 30], default: 10 },
    metric: {
      label: ${js(C.metricLabel)},
      effUnit: '€/M', // euros per million people
      /* Vatican City is 801 people: below 1,000 the count itself is shown */
      format: v => v >= 1 ? v.toFixed(1) + 'M' : v >= 0.001 ? Math.round(v * 1000).toLocaleString('en-US') + 'K' : String(Math.round(v * 1e6))
    },
    priceTable,
    economy: {
      budgets: ${js(CAL.budgets)},
      /* no \`endgame\`: when only one player has money left, that player takes every remaining lot for 1 each (the walkover in startLot) */
      sampling: 'random',
      bidSteps: [[12, [1, 2, 5, 10, 25]], [40, [2, 5, 10, 25, 50]], [100, [5, 10, 25, 50, 100]], [null, [10, 25, 50, 100, 200]]],
      typingBonus: 4
    },
    /* The Countries machinery (see CLAUDE.md "Economy and bot"), calibrated for this pool with \`node test/economy.js capitals\`. */
    bot: ${js(CAL.bot)},
    levels: [
      { id: 'beginner', label: ${js(C.levels.beginner)}, tag: 'europe' },
      { id: 'medium', label: ${js(C.levels.medium)}, minValue: ${CAL.mediumMin} },
      { id: 'expert', label: ${js(C.levels.expert)} }
    ],
    defaultLevel: 'medium',
    globe: { borders: true, claimBorders: false },
    taunts: {
      tiers: [{ id: 'mega', min: 10 }, { id: 'large', min: 3 }, { id: 'mid', min: 1 }, { id: 'small', min: 0.1 }, { id: 'micro', min: 0 }],
      generic: ${js(C.taunts)}
    },
    items: [
${items.map(i => '      ' + js(i)).join(',\n')}
    ]
  };
  if (typeof module === 'object' && module.exports) module.exports = pack;
  else root.Packs.register(pack);
})(typeof self !== 'undefined' ? self : this);
`;
return { pack, count: items.length };
}
module.exports = { CAL, build };
if (require.main === module && !process.env.NODE_TEST_CONTEXT) {   // `node --test` also runs every file in test/; the committed pack is checked by capitals.test.js instead
  const r = build();
  fs.writeFileSync(path.join(__dirname, '..', 'pack-capitals.js'), r.pack);
  console.log('wrote pack-capitals.js', Math.round(r.pack.length / 1024) + ' KB,', r.count, 'capitals');
}
