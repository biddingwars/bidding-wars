/* Generates ../pack-states.js from two committed inputs, so the pack can always be rebuilt and checked:
     test/census-nst-est2025.json  the official Census Bureau numbers (see its "source" and "vintage")
     test/states-content.json      names, USPS codes, centroids (Census boundaries), taunts, fun facts
   Run:  node test/make-pack-states.js          (the browser/engine tests fail if the pack drifts from the inputs) */
const fs = require('fs'), path = require('path');
const census = JSON.parse(fs.readFileSync(path.join(__dirname, 'census-nst-est2025.json'), 'utf8'));
const C = JSON.parse(fs.readFileSync(path.join(__dirname, 'states-content.json'), 'utf8'));

/* CAL = the calibration numbers (the committed ones). STATES_CAL (json) overrides them for a scratch run. */
const CAL = Object.assign({
  priceScale: 1,                                        // v43: an average lot is $10 (about $1.5 per million people at the fair price); it was 3 (an average lot $30)
  budgets: { 5: 20, 10: 35, 15: 50, 20: 70 },          // the clean table (owner): about $3.4 per lot, $170 for all 50 states = one dollar per million people for the two players together
  limitMul: { 5: 0.8, 10: 0.55, 15: 0.55, 20: 0.55 },
  spread: { 5: 0.06, 10: 0.06, 15: 0.05, 20: 0.04 },
  rollSpan: 0.4, noise: 0.15
}, JSON.parse(process.env.STATES_CAL || '{}'));
const LANGS = ['de', 'it', 'es', 'fr'];
const items = census.states.map(s => {
  const name = Object.assign({ en: s.name }, (C.names[s.name] || {}));
  const [lat, lon] = C.centroids[s.name];
  return { id: C.abbr[s.name], name, value: s.pop / 1e6, lat, lon, abbr: C.abbr[s.name] };
});
const facts = {};
census.states.forEach(s => { facts[C.abbr[s.name]] = { en: C.facts[s.name] }; });
const itemTaunts = C.items;

const pack = `/* ============================================================================
   pack-states.js — the "US States" content pack: the 50 states, population (millions)
   as the score. GENERATED by test/make-pack-states.js — edit the inputs, not this file.

   Population: ${census.source}, ${census.table}.
   ${census.vintage}, released ${census.release}. ${census.license}. 50 states only.
   Prices are in US dollars in every language (the pack's currency is $).
   Pack format: see CLAUDE.md "Adding a pack".
   ========================================================================== */
(function (root) {
  const pack = {
    id: 'states',
    title: ${JSON.stringify({ en: 'US States', de: 'US-Bundesstaaten', it: 'Stati USA', es: 'Estados de EE. UU.', fr: 'États américains' })},
    noun:  ${JSON.stringify({ en: 'state', de: 'Bundesstaat', it: 'stato', es: 'estado', fr: 'État' })},
    currency: { symbol: '$', code: 'USD', locale: 'en-US' },    // USD in every language
    budgetPerLot: 10,                       // nominal only: the real budgets are the table in economy.budgets
    lots: { options: [5, 10, 15, 20], default: 10 },    // capped at 20 on purpose (v40): a fixed-cap player beats the bot in 30-50-lot rounds (CLAUDE.md, "The stingy-player exploit"); the engine still draws any count

    /* ECONOMY (see CLAUDE.md "US States economy"). v43, owner: one dollar per million people. A player has $170 for all 50 states, so
       $20 / $35 / $50 / $70 for 5 / 10 / 15 / 20 lots (the clean table) and prices run at the original scale (priceScale 1: an average lot is $10,
       the smallest states $1-2, California $58). The money is scarce on purpose: the budget is about a third of the round's fair value, and the bot's
       limits (limitMul, below) were re-found for that ratio with the fine fixed-cap search of test/exploit.js. */
    economy: {
      priceScale: ${CAL.priceScale},
      budgets: ${JSON.stringify(CAL.budgets)},
      /* no endgame block: when only one player has money left, that player takes every remaining lot for $1 each (the walkover in startLot) - going all in is a risk on purpose */
      sampling: 'systematic',
      /* the five raise buttons grow with the current price (the item's fair price would leak its size) */
      bidSteps: [[12, [1, 2, 5, 10, 25]], [40, [2, 5, 10, 25, 50]], [100, [5, 10, 25, 50, 100]], [null, [10, 25, 50, 100, 200]]],
      typingBonus: 4                              // seconds added once per turn when the custom-amount field is used
    },
    /* The bot: Big-4 premium, paced spending, knockout awareness, temperament + mood. limitMul and spread are the
       calibration tables by lot count (test/economy.js re-measures them on the real engine). */
    bot: {
      limitMul: ${JSON.stringify(CAL.limitMul)},   // 15+ lots are tuned together with rollSpan (below): a player who never pays more than ~0.8x the fair price beat the old limits 76-100% of long rounds (see CLAUDE.md)
      rollSpan: ${CAL.rollSpan},                                   // the walk-away roll uses the first 40% of [ideal, max]: less lot-to-lot swing in the bot's limit, so no fixed-limit player out-earns it
      noise: ${CAL.noise},                                     // a little per-lot jitter on top, so the narrower roll does not make the drop-out point easy to read (0.15 keeps the exploit search under its limit; 0.25+ does not)
      premium: { top: 4, pct: 0.15 },
      pacing: { gamma: 0.5, lo: 0.7, hi: 1.5 },
      knockout: { kappa: 1.5 },
      mood: { k: 0.25, up: 0.2, down: 0.15 },
      temperaments: {
        weights: [25, 50, 25],                       // conservative / balanced / aggressive
        bigRank: 10,
        spread: ${JSON.stringify(CAL.spread)},   // +-% on the walk-away
        conservative: { step: 0.75, big: 0.95 },      // smaller raises, a little less for the biggest states
        aggressive: { step: 1.25, big: 1.05, reserveCap: 3 }   // bigger raises, more for the biggest states, spends deep
      }
    },
    metric: {
      label: ${JSON.stringify({ en: 'Population', de: 'Einwohner', it: 'Popolazione', es: 'Población', fr: 'Population' })},
      effUnit: '$/M',                       // dollars per million people
      effLabel: ${JSON.stringify({ en: '$ per million', de: '$ pro Million', it: '$ per milione', es: '$ por millón', fr: '$ par million' })},
      format: v => v >= 10 ? v.toFixed(1) + 'M' : v.toFixed(2) + 'M'
    },
    /* No difficulty filters: every state is eligible, and a round draws without replacement. */
    levels: [{ id: 'all', label: ${JSON.stringify({ en: 'All 50 states', de: 'Alle 50 Bundesstaaten', it: 'Tutti i 50 stati', es: 'Los 50 estados', fr: 'Les 50 États' })} }],
    defaultLevel: 'all',
    globe: { borders: false, claimBorders: false },
    map: 'us',                              // results show the US map (us-view.js) instead of the globe
    captionFacts: true,                     // the auction caption under the lot shows the state's fun fact instead of the rival's taunts and one-liners (owner, v43)

    /* Smooth pricing, no bands. Ideal = the state's share of the 50-state total x (10 x priceScale x 50),
       so the ideals of all 50 states add up to 50 average lots and the average lot is worth
       about $30 (priceScale 3). A tiny scale factor k makes the whole-dollar ideals (floor $1) sum to exactly that.
       Max = ideal x a multiplier that eases from about 2.0 (smallest state) to 1.35 (largest).
       Both never get cheaper as the population grows (checked here and in validatePack). */
    priceTable(items) {
      const per = 10 * pack.economy.priceScale, total = items.reduce((a, i) => a + i.value, 0), target = items.length * per;
      const vmin = Math.min(...items.map(i => i.value)), vmax = Math.max(...items.map(i => i.value));
      const mul = v => { const t = (Math.log(v) - Math.log(vmin)) / (Math.log(vmax) - Math.log(vmin)); return 1.35 + 0.65 * Math.pow(1 - t, 2); };
      const sumFor = k => items.reduce((a, i) => a + Math.max(1, Math.round(k * target * i.value / total)), 0);
      let lo = 0.5, hi = 1.5;
      for (let n = 0; n < 60; n++) { const mid = (lo + hi) / 2; sumFor(mid) < target ? lo = mid : hi = mid; }
      const k = (lo + hi) / 2, out = new Map();
      let runIdeal = 0, runMax = 0;
      items.slice().sort((a, b) => a.value - b.value).forEach(it => {
        const ideal = Math.max(runIdeal, Math.max(1, Math.round(k * target * it.value / total)));
        const max = Math.max(ideal, runMax, Math.round(ideal * mul(it.value)));
        out.set(it.id, { ideal, max }); runIdeal = ideal; runMax = max;
      });
      return out;
    },

    /* Population tiers in millions: 20+ (4 states), 10-20 (6), 5-10 (14), 2-5 (14), under 2 (12). */
    taunts: {
      tiers: ${JSON.stringify(C.tiers)},
      items: ${JSON.stringify(itemTaunts)},
      generic: ${JSON.stringify(C.generic)}
    },
    /* One kid-friendly fun fact per state, shown after the sale. Never about population. English first;
       other languages fall back to English. Sources and verification status: FACTS-SOURCES.md. */
    facts: ${JSON.stringify(facts)},
    items: [
${items.map(i => '      ' + JSON.stringify(i)).join(',\n')}
    ]
  };
  if (typeof module === 'object' && module.exports) module.exports = pack;
  else root.Packs.register(pack);
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'pack-states.js'), pack);
console.log('wrote pack-states.js', Math.round(pack.length / 1024) + ' KB,', items.length, 'states');
