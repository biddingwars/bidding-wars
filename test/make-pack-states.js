/* Generates ../pack-states.js from two committed inputs, so the pack can always be rebuilt and checked:
     test/census-nst-est2025.json  the official Census Bureau numbers (see its "source" and "vintage")
     test/states-content.json      names, USPS codes, centroids (Census boundaries), taunts, fun facts
   Run:  node test/make-pack-states.js          (the browser/engine tests fail if the pack drifts from the inputs) */
const fs = require('fs'), path = require('path');
const census = JSON.parse(fs.readFileSync(path.join(__dirname, 'census-nst-est2025.json'), 'utf8'));
const C = JSON.parse(fs.readFileSync(path.join(__dirname, 'states-content.json'), 'utf8'));

const LANGS = ['de', 'it', 'es', 'fr'];
const items = census.states.map(s => {
  const name = Object.assign({ en: s.name }, (C.names[s.name] || {}));
  const [lat, lon] = C.centroids[s.name];
  return { id: C.abbr[s.name], name, value: s.pop / 1e6, lat, lon, abbr: C.abbr[s.name] };
});
const facts = {};
census.states.forEach(s => { facts[C.abbr[s.name]] = { en: C.facts[s.name] }; });
const itemTaunts = C.items;

const pack = `/* ============================================================================
   pack-states.js — the "US States" content pack: the 50 states, population (millions)
   as the score. GENERATED by test/make-pack-states.js — edit the inputs, not this file.

   Population: ${census.source}, ${census.table}.
   ${census.vintage}, released ${census.release}. ${census.license}. 50 states only.
   Prices are in US dollars in every language (the pack's currency is $).
   Pack format: see CLAUDE.md "Adding a pack".
   ========================================================================== */
(function (root) {
  const pack = {
    id: 'states',
    title: ${JSON.stringify({ en: 'US States', de: 'US-Bundesstaaten', it: 'Stati USA', es: 'Estados de EE. UU.', fr: 'États américains' })},
    noun:  ${JSON.stringify({ en: 'state', de: 'Bundesstaat', it: 'stato', es: 'estado', fr: 'État' })},
    currency: { symbol: '$', code: 'USD', locale: 'en-US' },    // USD in every language
    budgetPerLot: 10,                       // 10 lots = $100; all 50 states = $500
    lots: { options: [5, 10, 15, 20, 30, 40, 50], default: 10, all: 50 },
    metric: {
      label: ${JSON.stringify({ en: 'Population', de: 'Einwohner', it: 'Popolazione', es: 'Población', fr: 'Population' })},
      effUnit: '$/M',                       // dollars per million people
      effLabel: ${JSON.stringify({ en: '$ per million', de: '$ pro Million', it: '$ per milione', es: '$ por millón', fr: '$ par million' })},
      format: v => v >= 10 ? v.toFixed(1) + 'M' : v.toFixed(2) + 'M'
    },
    /* No difficulty filters: every state is eligible, and a round draws without replacement. */
    levels: [{ id: 'all', label: ${JSON.stringify({ en: 'All 50 states', de: 'Alle 50 Bundesstaaten', it: 'Tutti i 50 stati', es: 'Los 50 estados', fr: 'Les 50 États' })} }],
    defaultLevel: 'all',
    globe: { borders: false, claimBorders: false },
    map: 'us',                              // results show the US map (us-view.js) instead of the globe

    /* Smooth pricing, no bands. Ideal = the state's share of the 50-state total x ($budgetPerLot x 50),
       so the ideals of all 50 states add up to one full round's budget and the average lot is worth
       about $10. A tiny scale factor k makes the whole-dollar ideals (floor $1) sum to exactly that.
       Max = ideal x a multiplier that eases from about 2.0 (smallest state) to 1.35 (largest).
       Both never get cheaper as the population grows (checked here and in validatePack). */
    priceTable(items) {
      const per = pack.budgetPerLot, total = items.reduce((a, i) => a + i.value, 0), target = items.length * per;
      const vmin = Math.min(...items.map(i => i.value)), vmax = Math.max(...items.map(i => i.value));
      const mul = v => { const t = (Math.log(v) - Math.log(vmin)) / (Math.log(vmax) - Math.log(vmin)); return 1.35 + 0.65 * Math.pow(1 - t, 2); };
      const sumFor = k => items.reduce((a, i) => a + Math.max(1, Math.round(k * target * i.value / total)), 0);
      let lo = 0.5, hi = 1.5;
      for (let n = 0; n < 60; n++) { const mid = (lo + hi) / 2; sumFor(mid) < target ? lo = mid : hi = mid; }
      const k = (lo + hi) / 2, out = new Map();
      let runIdeal = 0, runMax = 0;
      items.slice().sort((a, b) => a.value - b.value).forEach(it => {
        const ideal = Math.max(runIdeal, Math.max(1, Math.round(k * target * it.value / total)));
        const max = Math.max(ideal, runMax, Math.round(ideal * mul(it.value)));
        out.set(it.id, { ideal, max }); runIdeal = ideal; runMax = max;
      });
      return out;
    },

    /* Population tiers in millions: 20+ (4 states), 10-20 (6), 5-10 (14), 2-5 (14), under 2 (12). */
    taunts: {
      tiers: ${JSON.stringify(C.tiers)},
      items: ${JSON.stringify(itemTaunts)},
      generic: ${JSON.stringify(C.generic)}
    },
    /* One kid-friendly fun fact per state, shown after the sale. Never about population. English first;
       other languages fall back to English. Sources and verification status: FACTS-SOURCES.md. */
    facts: ${JSON.stringify(facts)},
    items: [
${items.map(i => '      ' + JSON.stringify(i)).join(',\n')}
    ]
  };
  if (typeof module === 'object' && module.exports) module.exports = pack;
  else root.Packs.register(pack);
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'pack-states.js'), pack);
console.log('wrote pack-states.js', Math.round(pack.length / 1024) + ' KB,', items.length, 'states');
